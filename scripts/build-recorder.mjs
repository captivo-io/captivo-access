import { build } from "esbuild";
import { writeFileSync } from "node:fs";

const result = await build({
  entryPoints: ["src/recorder/record-init.ts"],
  bundle: true,
  format: "iife",
  minify: true,
  target: ["es2019"],
  write: false,
});
const js = result.outputFiles[0].text;
writeFileSync("src/recorder/rec.bundle.ts", `// GENERATED by scripts/build-recorder.mjs — do not edit.\nexport const RECORDER_JS = ${JSON.stringify(js)};\n`);
console.log("recorder bundle:", js.length, "bytes");

// The isolated browser's session extension runs the same capture (src/recorder/keys.ts)
// as its content script; generated here so the masking rules have one source.
const ext = await build({
  entryPoints: ["src/recorder/kasm-keys-entry.ts"],
  bundle: true,
  format: "iife",
  minify: true,
  target: ["es2019"],
  write: false,
});
writeFileSync("kasm-browser/session-ext/content.js", "// GENERATED by scripts/build-recorder.mjs from src/recorder/kasm-keys-entry.ts — do not edit.\n" + ext.outputFiles[0].text);
console.log("kasm keys content script:", ext.outputFiles[0].text.length, "bytes");
